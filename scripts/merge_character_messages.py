FILES = {
    "OkScriptToolkitBundle.properties": EN,
    "OkScriptToolkitBundle_zh_CN.properties": ZH_CN,
    "OkScriptToolkitBundle_zh_TW.properties": ZH_TW,
    "OkScriptToolkitBundle_ja.properties": JA,
    "OkScriptToolkitBundle_ko.properties": KO,
    "OkScriptToolkitBundle_es.properties": ES,
}


def main() -> int:
    base = os.path.abspath(BASE)
    for name, values in FILES.items():
        if len(values) != len(KEYS):
            print(f"[FAIL] {name}: {len(values)} values vs {len(KEYS)} keys")
            return 1
        path = os.path.join(base, name)
        with open(path, encoding="utf-8") as fh:
            lines = fh.read().splitlines()
        existing = {line.split("=", 1)[0] for line in lines if "=" in line and not line.startswith("#")}
        added = []
        for key, value in zip(KEYS, values):
            if key in existing:
                continue
            added.append(f"{key}={value}")
        if not added:
            print(f"[skip] {name}")
            continue
        with open(path, "a", encoding="utf-8", newline="\n") as fh:
            if lines and lines[-1].strip():
                fh.write("\n")
            fh.write("\n".join(added) + "\n")
        print(f"[ok] {name}: +{len(added)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
